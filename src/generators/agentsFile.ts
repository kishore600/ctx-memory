import { access, readFile, writeFile } from "node:fs/promises";
import type { MemoryEntry } from "../core/schema.js";

const START_MARKER = "<!-- ctx-memory:start -->";
const END_MARKER = "<!-- ctx-memory:end -->";

function renderEntry(entry: MemoryEntry): string {
  const { title, date, refs, tags, status } = entry.frontmatter;
  const meta: string[] = [date];
  if (refs.length) meta.push(`refs: ${refs.join(", ")}`);
  if (tags.length) meta.push(`tags: ${tags.join(", ")}`);
  const badge = status !== "active" ? ` _(${status})_` : "";
  const firstLine = entry.body.split("\n").find((l) => l.trim().length > 0) ?? "";
  return `- **${title}**${badge} (${meta.join(" · ")})\n  ${firstLine}`;
}

function groupByTag(entries: MemoryEntry[]): Map<string, MemoryEntry[]> {
  const groups = new Map<string, MemoryEntry[]>();
  for (const entry of entries) {
    const tags = entry.frontmatter.tags.length ? entry.frontmatter.tags : ["general"];
    for (const tag of tags) {
      if (!groups.has(tag)) groups.set(tag, []);
      groups.get(tag)!.push(entry);
    }
  }
  return groups;
}

export function renderMemorySection(entries: MemoryEntry[]): string {
  const active = entries.filter((e) => e.frontmatter.status !== "superseded");
  if (active.length === 0) {
    return [START_MARKER, "## Project Memory", "", "_No memory entries yet. Run `memory capture` to add one._", END_MARKER].join(
      "\n"
    );
  }

  const groups = groupByTag(active);
  const lines: string[] = [
    START_MARKER,
    "## Project Memory",
    "",
    "Captured decisions and context for this repo. Generated by `memory generate` — do not edit inside this block, it will be overwritten.",
    "",
  ];

  const sortedTags = [...groups.keys()].sort();
  for (const tag of sortedTags) {
    lines.push(`### ${tag}`, "");
    for (const entry of groups.get(tag)!) {
      lines.push(renderEntry(entry));
    }
    lines.push("");
  }

  lines.push(END_MARKER);
  return lines.join("\n").replace(/\n{3,}/g, "\n\n");
}

export async function upsertMemorySection(filePath: string, section: string): Promise<"created" | "updated"> {
  let existing = "";
  let created = false;
  try {
    existing = await readFile(filePath, "utf8");
  } catch {
    created = true;
  }

  if (created) {
    await writeFile(filePath, section + "\n", "utf8");
    return "created";
  }

  const startIdx = existing.indexOf(START_MARKER);
  const endIdx = existing.indexOf(END_MARKER);

  let next: string;
  if (startIdx !== -1 && endIdx !== -1) {
    next = existing.slice(0, startIdx) + section + existing.slice(endIdx + END_MARKER.length);
  } else {
    const sep = existing.endsWith("\n") ? "\n" : "\n\n";
    next = existing + sep + section + "\n";
  }

  await writeFile(filePath, next, "utf8");
  return "updated";
}

export async function fileExists(filePath: string): Promise<boolean> {
  try {
    await access(filePath);
    return true;
  } catch {
    return false;
  }
}
